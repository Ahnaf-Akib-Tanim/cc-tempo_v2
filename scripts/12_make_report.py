"""Step 12: collect every results/ folder into one markdown report (RESULTS_REPORT.md) + figures.

Run locally after unzipping the Kaggle outputs into the project (see TODO_PLAN.md):
    python scripts/12_make_report.py --root .
"""
import _common
import glob
import os

import pandas as pd

p = _common.parser(__doc__)
args = p.parse_args()
root = args.root
lines = ["# CC-Tempo v2 - results report", "", "Auto-generated by scripts/12_make_report.py. Numbers are means over seeds;",
         "see the CSVs for SDs and per-run values.", ""]


def table(df, n=40):
    try:
        return df.head(n).to_markdown(index=False)
    except Exception:  # tabulate not installed
        return "```\n" + df.head(n).to_string(index=False) + "\n```"


for res in sorted(glob.glob(os.path.join(root, "work", "*", "results"))):
    ds = os.path.basename(os.path.dirname(res))
    lines += [f"## {ds}", ""]
    f = os.path.join(res, "runs_long.csv")
    if os.path.exists(f):
        df = pd.read_csv(f)
        cols = [c for c in ["mc_pcc", "mc_pcc_masked", "mc_spearman", "mc_auroc", "mc_mae", "pi_pcc"] if c in df]
        cols += [c for c in df.columns if c.startswith(("w2_t", "l1_t", "kl_bits_t"))][:6]
        if cols:
            g = df.groupby(["model", "condition"])[cols].mean().round(4).reset_index()
            n = df.groupby(["model", "condition"]).size().rename("n_seeds").reset_index()
            lines += ["### Model comparison", "", table(g.merge(n)), ""]
    for name in ["stats_bootstrap.csv", "stats_seed.csv", "baselines_long.csv", "synthetic_summary.csv",
                 "evidence_clone_matched.csv"]:
        f = os.path.join(res, name)
        if os.path.exists(f):
            df = pd.read_csv(f)
            if name == "baselines_long.csv":
                df = df.groupby(["model", "condition"]).mean(numeric_only=True).round(4).reset_index()
            lines += [f"### {name}", "", table(df.round(4)), ""]
    for d in sorted(glob.glob(os.path.join(res, "interpret_*")) + glob.glob(os.path.join(res, "analysis_*"))):
        lines += [f"### {os.path.basename(d)}", ""]
        for f in sorted(glob.glob(os.path.join(d, "*.csv")))[:12]:
            if "basins_alpha" in f:
                continue
            lines += [f"**{os.path.basename(f)}**", "", table(pd.read_csv(f).round(4), 15), ""]
out = os.path.join(root, "results", "RESULTS_REPORT.md")
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w", encoding="utf-8") as fh:
    fh.write("\n".join(lines))
print("wrote", out)
